const catalogs: Record<Locale, Record<MessageKey, string>> = { en, fr };

export function translate(
  locale: Locale,
  key: MessageKey,
  vars?: Record<string, string | number>
): string {
  let text = catalogs[locale]?.[key] ?? en[key] ?? String(key);
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.split(`{${k}}`).join(String(v));
    }
  }
  return text;
}

/** Safe lookup when the key is built dynamically (enums). */
export function translateDynamic(
  locale: Locale,
  key: string,
  fallback?: string,
  vars?: Record<string, string | number>
): string {
  if (key in en) {
    return translate(locale, key as MessageKey, vars);
  }
  return fallback ?? key;
}
